#include <stdio.h>

int main (void)
{
    /**
     * '\q' не является допустимой escape-последовательностью
     * стандартного C.
     *
     * GCC выдаёт предупреждение:
     * "unknown escape sequence: '\q'"
     *
     * В данной реализации компилятор продолжает сборку,
     * а при выводе получается символ 'q'.
     * Полагаться на такое поведение переносимая C-программа не должна.
     */
    printf("hello\qworld\n");

    return 0;
}
